// 非地面（障碍物）检测：纯函数，无 PCL / 无 ROS 依赖，可独立自检。
//
// 动机：1.2 的趋势相对开窗只解决"哪些点算地面"，但没把"明显高出路面的东西"
// 单独挑出来。主动悬架需要区分"该吸收的路面凸起（减速带、井盖）"和"不该当
// 路面的障碍（路沿石、低矮桩、行人腿）"。后者若混进剖面，会让前馈误以为
// 前方是连续路面而去做预瞄——实则应当触发"语义预瞄"分支（未来工作：避让 /
// 减速），而不是压路。
//
// 做法：给定每格的地面参考高度（剖面估计；缺格时用趋势线补），扫描轮迹 ROI
// 内的点，凡是高于参考地面超过阈值、且数量足够稳定的，聚合成一个障碍物，
// 记录其位置、相对地面高度与沿前进方向的半宽。这些点本身不参与地面剖面
// 估计（已被开窗排除），这里只是把它们"回收"成结构化输出，留给上层做
// 语义级决策，而不是一锅煮进高度剖面。
//
// 本模块只处理**正障碍**（高出路面的东西）。坑洼/桥缝这类**负障碍**需要另一套
// 判据（依赖多帧地面模型、车速与悬挂响应，单帧阈值无法区分"路面下沉"与
// "车体俯仰"），不在本函数职责内；`interpolate_gaps=true` 还会把长空洞直线
// 插值填平，负障碍更容易被伪造成路面——这一点在参数校验里会给出非致命告警。
#pragma once

#include <cstddef>
#include <utility>
#include <vector>

namespace suspension_preview_v2 {

struct Obstacle {
    double x_m = 0.0;          // 沿车前进方向的距离 (m)，取障碍簇所占格区间的中心
    double lateral_m = 0.0;    // 横向偏移 (m)，相对车体中心，左负右正
    double height_m = 0.0;     // 相对地面的代表高度 (m)：簇内候选点残差的中位数。
                               // 取中位数而不是单点最大值：一个飞点/反光点不应
                               // 决定"这个障碍有多高"（旧实现取 max，一个 1.9 m
                               // 的噪声点能把 10 cm 的路沿报成 1.9 m 障碍）
    double half_width_m = 0.0; // 沿前进方向的半宽 (m)：障碍簇跨过的格区间半宽。
                               // 相邻候选格合并后统计，跨格障碍不再被压成
                               // "单格半宽 ≤ 2.5 cm"（旧实现逐格输出，5 cm 格
                               // 的半宽上限恒为 2.5 cm，与 msg 注释的"半宽"不符）
};

// ground_ref：每格地面参考高度，与剖面同分辨率（spacing）；NaN 表示该格无
//             地面模型，该格的点不参与判定（避免在没有地面参考时把噪声
//             误判成障碍）
// points：该轮迹 ROI 内的 (x, z) 点；z 应为有限值，调用方负责初筛
// spacing：纵向分辨率 (m)
// lane_center_m：该轮迹的横向中心（写入 Obstacle.lateral_m）
// min_height_m：高于地面多少才算障碍物候选 (m)。必须为有限正数，否则返回空：
//             填 0/负数时"任何点（甚至地面点）都算障碍"，输出只剩噪声
// min_points：一个**障碍簇**（相邻候选格合并后）至少多少候选点才算稳定障碍物。
//             注意旧语义是"单格至少多少点"：5 cm 格在 5 m 处通常只有 2 个点，
//             按格判 4 点等于把远处障碍全漏掉；按簇判既保住稳定性，又跟点密度
//             解耦。min_points < 1 时返回空（否则空簇也会被输出成 0 高度障碍）
//
// 检测流程：逐格统计候选点 -> 相邻候选格合并成簇 -> 簇内总点数达标才输出。
// 空一格就断开：漏合并只会把一个大障碍拆成两个，而误合并会把两个独立障碍
// 连成一个、半宽和位置都失真——两害相权取其轻。
std::vector<Obstacle> detect_lane_obstacles(
    const std::vector<float>& ground_ref,
    const std::vector<std::pair<float, float>>& points,
    double spacing, double lane_center_m,
    double min_height_m, int min_points);

}  // namespace suspension_preview_v2
